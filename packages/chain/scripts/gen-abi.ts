// Regenerates src/abi.ts and src/bytecode.ts from the Foundry build (run `forge build` first):
//   bun packages/chain/scripts/gen-abi.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const out = join(import.meta.dir, "../../../contracts/out");
const names = ["ThesisSeal", "StampRoots", "CallerShare", "ProvisoSwapAdapter"];
const read = (n: string) => JSON.parse(readFileSync(join(out, `${n}.sol`, `${n}.json`), "utf8"));

const header = "// Generated by scripts/gen-abi.ts from contracts/out. Do not edit.\n";
writeFileSync(
  join(import.meta.dir, "../src/abi.ts"),
  header + names.map((n) => `export const ${n[0].toLowerCase() + n.slice(1)}Abi = ${JSON.stringify(read(n).abi)} as const;\n`).join(""),
);
// Bytecode is only for local deploys (tests, scripts); production deploys go through forge script.
writeFileSync(
  join(import.meta.dir, "../src/bytecode.ts"),
  header + names.map((n) => `export const ${n[0].toLowerCase() + n.slice(1)}Bytecode = "${read(n).bytecode.object}" as const;\n`).join(""),
);
console.log("abi + bytecode written for", names.join(", "));
